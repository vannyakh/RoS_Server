"""Write bigworld_gateway/.env from RoS_Server/.env (ROS_API_URL, GATEWAY_API_KEY). No secrets printed."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / ".env"
DST = ROOT / "bigworld_gateway" / ".env"

KEEP = ("ROS_API_URL", "GATEWAY_API_KEY", "ROS_API_TIMEOUT", "ROS_API_CONNECT_TIMEOUT")


def parse_env(path: Path) -> dict[str, str]:
    data: dict[str, str] = {}
    if not path.is_file():
        return data
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        data[key.strip()] = value.strip()
    return data


def main() -> int:
    src = parse_env(SRC)
    if not src.get("GATEWAY_API_KEY"):
        print("sync_gateway_env: GATEWAY_API_KEY empty in .env — gateway link stays off")
    defaults = {
        "ROS_API_URL": "http://127.0.0.1:8000",
        "GATEWAY_API_KEY": src.get("GATEWAY_API_KEY", ""),
        "ROS_API_TIMEOUT": src.get("ROS_API_TIMEOUT", "2"),
    }
    for key in KEEP:
        if key in src:
            defaults[key] = src[key]
    lines = [
        "# Generated by scripts/sync_gateway_env.py — do not commit if it contains secrets.",
        "# Re-run after you change GATEWAY_API_KEY in RoS_Server/.env",
        "",
    ]
    for key in KEEP:
        if key in defaults and defaults[key] != "":
            lines.append(f"{key}={defaults[key]}")
        elif key in defaults:
            lines.append(f"{key}={defaults[key]}")
    lines.extend(
        [
            "",
            "# Operator sign-in is RoS_Server/.env only (ADMIN_USERNAME / ADMIN_PASSWORD).",
            "",
        ]
    )
    DST.write_text("\n".join(lines), encoding="utf-8")
    print(f"sync_gateway_env: wrote {DST.relative_to(ROOT)} ({sum(1 for k in KEEP if defaults.get(k))} keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())